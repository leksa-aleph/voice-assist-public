"""
Задержка по этапам. Этап - разница двух моментов time.monotonic(), в
секундах; хранятся последние N значений каждого этапа, наружу - медиана и
90-й процентиль. Этапы не складываются: у каждого своя выборка.

Слова:
  audio_queue   блок отдан драйвером (_enqueue) -> взят потоком VAD
  stt_wait      окно поставлено в очередь распознавания -> распознавание началось
  infer         одно распознавание (вызов recognize, батч окон)
  word_arrive   конец слова в звуке -> слово пришло в оверлей
  word_pace     слово пришло в оверлей -> показано (очередь темпа чтения)
  word_total    конец слова в звуке -> слово показано
Перевод:
  tr_confirm    конец последнего слова куска в звуке -> кусок отдан переводчику
  tr_queue      отдан переводчику -> перевод начат
  tr_infer      один перевод (предложение или черновик)
  tr_total      конец последнего исходного слова, вошедшего в перевод
                (черновик или чистовой) -> новые слова этого перевода показаны
  gpu_wait      живые субтитры ждали видеокарту (её занимала расшифровка файла)
  gpu_wait_file расшифровка файла ждала видеокарту

Конец слова в звуке = момент, когда драйвер отдал блок, где фраза началась,
плюс время слова внутри фразы по меткам модели (точность ~40-80 мс). Сколько
звук шёл от микрофона или приложения до драйвера - отсюда не видно.
Показано = слово вышло в ленту оверлея; сам кадр рисуется до 33 мс позже.
"""
from __future__ import annotations

import collections
import threading

N = 300

_lock = threading.Lock()
_data: dict[str, collections.deque] = {}


def add(stage: str, seconds: float):
    with _lock:
        d = _data.get(stage)
        if d is None:
            d = _data[stage] = collections.deque(maxlen=N)
        d.append(float(seconds))


def summary() -> dict[str, tuple[float, float, int]]:
    """{этап: (медиана, p90, сколько замеров)} в секундах."""
    with _lock:
        items = {k: sorted(v) for k, v in _data.items() if v}
    return {k: (v[len(v) // 2], v[min(len(v) - 1, int(len(v) * 0.9))], len(v)) for k, v in items.items()}


def reset():
    with _lock:
        _data.clear()
